// Run after replacing a bundled illustration. Native/web reference one shared
// image file; the data URI fallback is retained for non-bundling consumers.
const {readFile, writeFile} = require('node:fs/promises');
const {join} = require('node:path');
const sharp = require('sharp');

(async () => {
  const directory = join(__dirname, '../src/ui/images');
  for (const [module, exported, names] of [
    ['libraryPreview', 'libraryPreviewAtlas', ['library-preview.jpg']],
    ['nightLibraryCover', 'nightLibraryCover', ['night-library-cover.jpg']],
    ['galleryArtwork', 'galleryArtwork', ['night-library-reading.jpg', 'night-library-room.jpg']],
  ]) {
    const sizes = [], fallback = [];
    for (const name of names) {
      const bytes = await readFile(join(directory, name));
      const {width, height} = await sharp(bytes).metadata();
      sizes.push({width, height});
      fallback.push({uri: `data:image/jpeg;base64,${bytes.toString('base64')}`, width, height});
    }
    const array = module === 'galleryArtwork';
    const value = rows => array ? `[${rows.join(', ')}]` : rows[0];
    const header = '// Generated by scripts/generate-library-preview.cjs.\n';
    await writeFile(join(directory, `${module}.ts`), header +
      `export const ${exported} = ${JSON.stringify(array ? fallback : fallback[0])} as const;\n`);
    await writeFile(join(directory, `${module}.native.ts`), header + "import {Image} from 'react-native';\n" +
      `export const ${exported} = ${value(names.map(name => `Image.resolveAssetSource(require('./${name}'))`))};\n`);
    await writeFile(join(directory, `${module}.web.ts`), header +
      names.map((name, index) => `import image${index} from './${name}';\n`).join('') +
      `export const ${exported} = ${value(sizes.map((size, index) => `{uri: image${index}, width: ${size.width}, height: ${size.height}}`))} as const;\n`);
  }
})().catch(error => {console.error(error); process.exitCode = 1;});
